"""Write installer/models.iss: languages, model routes and packages for the installer's language page.

    python tools/gen_installer_models.py
Run it after changing keept/translate/catalog.json or keept/translate/models_manifest.json
(tests/test_installer_models.py fails while the generated file is out of date).
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from keept.languages import LANGUAGES  # noqa: E402
from keept.translate.models import CATALOG, MANIFEST  # noqa: E402
from keept.translate.translator import route  # noqa: E402

OUT = ROOT / "installer" / "models.iss"


def render() -> str:
    catalog = CATALOG
    models = MANIFEST["models"]
    base = MANIFEST["base_url"]
    codes = list(LANGUAGES)
    pairs = sorted(f"{s}-{t}" for s, t in catalog)
    missing = [p for p in pairs if p not in models]
    if missing:
        raise SystemExit(f"models missing from the manifest: {missing}")
    q = lambda s: "'" + s.replace("'", "''") + "'"  # noqa: E731
    out = [
        "// Generated by tools/gen_installer_models.py from the model catalog and the manifest",
        "// pinned in the app (keept/translate). Do not edit by hand.",
        "",
        "var",
        "  LangCodes, LangNames: array of String;",
        "  PairCodes, PairUrls, PairShas: array of String;",
        "  PairSizes: array of Int64;",
        "",
        "procedure KeepTInitModels;",
        "begin",
        f"  SetArrayLength(LangCodes, {len(codes)});",
        f"  SetArrayLength(LangNames, {len(codes)});",
    ]
    for i, code in enumerate(codes):
        out.append(f"  LangCodes[{i}] := {q(code)}; LangNames[{i}] := {q(LANGUAGES[code].native)};")
    out += [f"  SetArrayLength(PairCodes, {len(pairs)});", f"  SetArrayLength(PairUrls, {len(pairs)});",
            f"  SetArrayLength(PairShas, {len(pairs)});", f"  SetArrayLength(PairSizes, {len(pairs)});"]
    for i, p in enumerate(pairs):
        m = models[p]
        out.append(f"  PairCodes[{i}] := {q(p)}; PairSizes[{i}] := {int(m['size'])};")
        out.append(f"  PairUrls[{i}] := {q(base + m['file'])};")
        out.append(f"  PairShas[{i}] := {q(m['sha256'])};")
    out += ["end;", "", "// Packages to translate Src into Tgt, comma separated (through English when needed).",
            "function KeepTRoute(const Src, Tgt: String): String;", "begin", "  Result := '';"]
    for s in codes:
        for t in codes:
            if s != t:
                chain = ",".join(f"{a}-{b}" for a, b in route(s, t, set(catalog)))
                out.append(f"  if (Src = {q(s)}) and (Tgt = {q(t)}) then Result := {q(chain)};")
    out += ["end;", ""]
    return "\r\n".join(out)


def main() -> int:
    OUT.write_text(render(), encoding="utf-8-sig", newline="")
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
